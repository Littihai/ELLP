export function tr(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  const e = DICT[key];
  let s = e ? e[lang] : key;
  if (vars) for (const k in vars) s = s.replace(new RegExp(`\\{${k}\\}`, "g"), String(vars[k]));
  return s;
}
